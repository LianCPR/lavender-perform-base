// Generates supabase/seed.sql from packages/music-library/src/demoCatalog.ts so
// the shared catalog rows exist in Postgres (playlists/favorites reference them
// by client_key). Run: node --experimental-strip-types scripts/generate-catalog-seed.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const { demoCatalog } = await import(
  pathToFileURL(resolve(root, 'packages/music-library/src/demoCatalog.ts')).href
);

const uuidFor = (value) => {
  const hex = createHash('md5').update(value).digest('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-8${hex.slice(
    17,
    20,
  )}-${hex.slice(20, 32)}`;
};
const q = (value) => (value === undefined || value === null ? 'null' : `'${String(value).replace(/'/g, "''")}'`);

const lines = [
  '-- Generated by scripts/generate-catalog-seed.mjs — do not edit by hand.',
  '-- Seeds the shared demo catalog so client keys resolve in every environment.',
  '',
];

const artistIds = new Map();
for (const artist of demoCatalog.artists) {
  const id = uuidFor(`artist:${artist.name}`);
  artistIds.set(artist.id, id);
  lines.push(
    `insert into public.artists (id, name) values ('${id}', ${q(artist.name)}) on conflict do nothing;`,
  );
}

for (const genre of demoCatalog.genres) {
  lines.push(
    `insert into public.genres (id, name) values ('${uuidFor(`genre:${genre.name}`)}', ${q(
      genre.name,
    )}) on conflict do nothing;`,
  );
}

const albumIds = new Map();
for (const album of demoCatalog.albums) {
  const id = uuidFor(`album:${album.artistName}:${album.title}`);
  albumIds.set(album.id, id);
  const genre = album.genreId
    ? `'${uuidFor(`genre:${demoCatalog.genres.find((item) => item.id === album.genreId)?.name ?? album.genreId}`)}'`
    : 'null';
  lines.push(
    `insert into public.albums (id, artist_id, title, year, genre_id) values ('${id}', ${
      album.artistId ? `'${artistIds.get(album.artistId)}'` : 'null'
    }, ${q(album.title)}, ${album.year ?? 'null'}, ${genre}) on conflict do nothing;`,
  );
}

for (const track of demoCatalog.tracks) {
  lines.push(
    `insert into public.tracks (client_key, title, artist_id, album_id, duration_sec, palette, source) values (${q(
      track.id,
    )}, ${q(track.title)}, ${
      track.artistId ? `'${artistIds.get(track.artistId)}'` : 'null'
    }, ${track.albumId ? `'${albumIds.get(track.albumId)}'` : 'null'}, ${
      track.durationSec
    }, ${q(track.palette)}, 'catalog') on conflict do nothing;`,
  );
}

writeFileSync(resolve(root, 'supabase/seed.sql'), `${lines.join('\n')}\n`);
console.log(`Wrote supabase/seed.sql (${demoCatalog.tracks.length} tracks)`);
